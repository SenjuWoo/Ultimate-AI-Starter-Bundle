<#
Install a pre-push hook that refuses a stale release manifest.

CI cannot know that a local install or test run added an archive after you
generated MANIFEST.json -- but the push can. The hook regenerates the metadata
and blocks the push when MANIFEST.json changed, so the red run never happens.
#>
[CmdletBinding()]
param([string]$PackRoot)
if (-not $PackRoot) {
  $PackRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
  if ((Split-Path -Leaf $PackRoot) -eq 'TOOLS') { $PackRoot = Split-Path -Parent $PackRoot }
}

$ErrorActionPreference = 'Stop'
$gitDir = Join-Path $PackRoot '.git'
if (-not (Test-Path -LiteralPath $gitDir -PathType Container)) {
  Write-Host 'No .git directory: this is not a checkout, nothing to install.' -ForegroundColor Yellow
  exit 0
}
$hooks = Join-Path $gitDir 'hooks'
New-Item -ItemType Directory -Force -Path $hooks | Out-Null
$hook = Join-Path $hooks 'pre-push'

$body = @'
#!/bin/sh
# Refuse a push whose MANIFEST.json no longer matches the tree.
root=$(git rev-parse --show-toplevel) || exit 1
powershell -NoProfile -ExecutionPolicy Bypass -File "$root/TOOLS/Refresh-Release-Metadata.ps1" -PackRoot "$root" || exit 1
if ! git diff --quiet -- MANIFEST.json; then
  echo "MANIFEST.json was regenerated by the pre-push check; commit it and push again." >&2
  exit 1
fi
'@

[IO.File]::WriteAllText($hook, ($body -replace "`r?`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Installed $hook" -ForegroundColor Green
