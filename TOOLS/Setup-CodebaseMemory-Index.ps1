$vendorRe = '\\(extern|external|vcpkg_installed|node_modules|build|dist|obj|__pycache__|site-packages)\\'
$codeExt = @('.h', '.hpp', '.cpp', '.c', '.cs', '.py', '.ts', '.tsx', '.js', '.jsx',
             '.psc', '.ps1', '.go', '.rs', '.rb', '.java', '.lua', '.php', '.swift')
$compiledExt = @('.h', '.hpp', '.cpp', '.c', '.cs', '.rs', '.go')

function Measure-Source {
    param([string]$Dir, [string[]]$Ext)
    $n = @(Get-ChildItem -LiteralPath $Dir -Recurse -File -Force -ErrorAction SilentlyContinue |
           Where-Object { $Ext -contains $_.Extension.ToLower() -and $_.FullName -notmatch $vendorRe }).Count
    return $n
}

function Get-ActiveVersionName {
    param([string]$ProjectRoot, $Snapshots)
    $active = $null
    $cur = Join-Path $ProjectRoot 'CURRENT.txt'
    if (Test-Path -LiteralPath $cur) {
        $txt = (Get-Content -LiteralPath $cur -TotalCount 3 -ErrorAction SilentlyContinue) -join ' '
        $m = [regex]::Match($txt, '\d+\.\d+(\.\d+)?')
        if ($m.Success) { $active = $m.Value }
    }
    if ($active) {
        $hit = @($Snapshots | Where-Object { $_.Name -match [regex]::Escape($active) })
        if ($hit.Count -gt 0) { return [string]$hit[0].Name }
    }
    # No CURRENT.txt (or it names no existing folder): fall back to the HIGHEST
    # version, never the newest mtime - a touched old folder is not the active one.
    $sorted = @($Snapshots | Sort-Object @{ Expression = {
        $mm = [regex]::Match($_.Name, '\d+\.\d+(\.\d+)?')
        if ($mm.Success) {
            $v = $mm.Value
            $dots = ($v.ToCharArray() | Where-Object { $_ -eq '.' }).Count
            if ($dots -lt 2) { $v = $v + '.0' }
            try { [version]$v } catch { [version]'0.0.0' }
        } else { [version]'0.0.0' }
    } } -Descending)
    return [string]$sorted[0].Name
}

function Get-PreservedCustom {
    # Returns the custom rule lines of an existing .cbmignore: everything that
    # is not base-template content (matched by trimmed text) and not inside the
    # generated snapshot block (which starts at $marker and runs to EOF).
    param([string]$ExistingPath)
    $out = @()
    if (-not (Test-Path -LiteralPath $ExistingPath)) { return , @() }
    $baseSet = New-Object 'System.Collections.Generic.HashSet[string]'
    foreach ($l in ($baseIgnore -split "`r?`n")) { [void]$baseSet.Add($l.Trim()) }
    [void]$baseSet.Add('# --- custom rules (preserved across re-runs; edit freely) ---')
    foreach ($line in (Get-Content -LiteralPath $ExistingPath -ErrorAction SilentlyContinue)) {
        if ($line -eq $marker) { break }
        if ($line -match '^#\s*(\.cbmignore|Generated by|MATCHING|Asset rules are|---)') { continue }
        if ([string]::IsNullOrWhiteSpace($line)) { continue }
        if ($baseSet.Contains($line.Trim())) { continue }
        $out += $line
    }
    return , @($out)
}

function Set-ProjectIgnore {
    param([string]$ProjectRoot)

    $name = Split-Path $ProjectRoot -Leaf
    $lines = $baseIgnore -split "`r?`n"

    # Custom rules survive re-runs: everything in the existing file that is not
    # base-template content and not inside the generated snapshot block is
    # carried forward, plus anything passed via -ExtraIgnore.
    $custom = @(Get-PreservedCustom -ExistingPath (Join-Path $ProjectRoot '.cbmignore'))
    foreach ($x in $ExtraIgnore) { if (-not ($custom -contains $x)) { $custom += $x } }
    # Guarantee one rule per element even if anything upstream returned a joined string.
    $custom = @($custom | ForEach-Object { $_ -split "`r?`n" } | Where-Object { $_.Trim().Length -gt 0 })

    $snapshots = @(Get-ChildItem -LiteralPath $ProjectRoot -Directory -Force -ErrorAction SilentlyContinue |
                   Where-Object { $_.Name -match '\d+\.\d+' })

    $keepName = $null
    $alsoKeep = @()
    $stale = @()

    if ($snapshots.Count -ge 2) {
        $keepName = Get-ActiveVersionName -ProjectRoot $ProjectRoot -Snapshots $snapshots
        $keepDir = Join-Path $ProjectRoot $keepName

        $keepCode = Measure-Source -Dir $keepDir -Ext $codeExt
        $keepComp = Measure-Source -Dir $keepDir -Ext $compiledExt

        # Active version may be a packaged release; find the real source carrier.
        if ($keepCode -lt 5 -or $keepComp -eq 0) {
            $useCompiled = ($keepComp -eq 0 -and $keepCode -ge 5)
            $best = $null; $bestN = 0
            foreach ($d in $snapshots) {
                if ([string]$d.Name -eq $keepName) { continue }
                if ($useCompiled) { $n = Measure-Source -Dir $d.FullName -Ext $compiledExt }
                else              { $n = Measure-Source -Dir $d.FullName -Ext $codeExt }
                if ($n -gt $bestN) { $bestN = $n; $best = [string]$d.Name }
            }
            if ($best -and $bestN -ge 5) {
                $alsoKeep += $best
                if ($useCompiled) { $why = 'active carries no compiled-language source' }
                else { $why = ("active is nearly empty (code={0})" -f $keepCode) }
                Write-UabsWarn ("{0}: {1} -> also keeping '{2}' ({3} files)" -f $name, $why, $best, $bestN)
            }
        }

        $stale = @($snapshots | Where-Object {
            [string]$_.Name -ne $keepName -and $alsoKeep -notcontains [string]$_.Name })
    }

    if ($custom.Count -gt 0) {
        $lines += ''
        $lines += '# --- custom rules (preserved across re-runs; edit freely) ---'
        $lines += $custom
    }

    if ($stale.Count -gt 0) {
        $lines += ''
        $lines += $marker
        $lines += ("# active = {0}" -f $keepName)
        foreach ($k in $alsoKeep) { $lines += ("# source carrier kept = {0}" -f $k) }
        foreach ($s in $stale) { $lines += ([string]$s.Name + '/') }
    }

    $target = Join-Path $ProjectRoot '.cbmignore'
    if ($Apply) {
        Set-Content -LiteralPath $target -Value $lines -Encoding UTF8
        Write-UabsOk ("{0}  (snapshots: {1} kept, {2} excluded; custom: {3})" -f $name, (1 + $alsoKeep.Count), $stale.Count, $custom.Count)
    }
    else {
        Write-Host ("  WOULD WRITE  {0}  (snapshots: {1} kept, {2} excluded; custom: {3})" -f `
            $name, (1 + $alsoKeep.Count), $stale.Count, $custom.Count)
    }
}

function Get-CbmExe {
    if ($CbmExe) { return $CbmExe }
    if ($env:CODEBASE_MEMORY_MCP -and (Test-Path -LiteralPath $env:CODEBASE_MEMORY_MCP)) { return $env:CODEBASE_MEMORY_MCP }
    $p = Join-Path $env:LOCALAPPDATA 'Programs\codebase-memory-mcp\codebase-memory-mcp.exe'
    if (Test-Path -LiteralPath $p) { return $p }
    return $null
}

function Invoke-CbmIndex {
    param([string]$Exe, [string]$ProjectRoot, [string]$Mode)
    $name = Split-Path $ProjectRoot -Leaf
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $line = & $Exe cli --quiet index_repository --repo-path $ProjectRoot --mode $Mode --name $name 2>$null |
            Where-Object { $_ -match '^\s*\{' } | Select-Object -Last 1
    $sw.Stop()
    $d = $null
    try { $d = $line | ConvertFrom-Json } catch { }
    if (-not $d -or -not $d.status) {
        return [pscustomobject]@{ Name = $name; Secs = [int]$sw.Elapsed.TotalSeconds; Nodes = $null; Edges = $null; Excluded = $null; Status = 'FAILED' }
    }
    return [pscustomobject]@{
        Name = $name; Secs = [int]$sw.Elapsed.TotalSeconds
        Nodes = $d.nodes; Edges = $d.edges
        Excluded = if ($d.excluded) { $d.excluded.count } else { 0 }
        Status = [string]$d.status
    }
}

# --- main -------------------------------------------------------------------

. (Join-Path $PSScriptRoot 'UABS-Common.ps1')

if (-not (Test-Path -LiteralPath $Path)) { throw "Path not found: $Path" }

Write-UabsStep ("codebase-memory index scope  ->  {0}" -f $Path)
if (-not $Apply) { Write-UabsWarn 'DRY RUN - no files written. Re-run with -Apply.' }

$targets = @()
if ($Recurse) {
    $targets = @(Get-ChildItem -LiteralPath $Path -Directory -Force -ErrorAction SilentlyContinue |
                 Where-Object { $ExcludeName -notcontains $_.Name -and -not $_.Name.StartsWith('.') } |
                 Select-Object -ExpandProperty FullName)
}
else {
    $targets = @($Path)
}

foreach ($t in $targets) { Set-ProjectIgnore -ProjectRoot $t }

Write-Host ''
Write-UabsStep ("{0} project(s) processed" -f $targets.Count)

if ($Index) {
    $exe = Get-CbmExe
    if (-not $exe) {
        Write-UabsWarn 'codebase-memory-mcp.exe not found (set CODEBASE_MEMORY_MCP or pass -CbmExe); skipping -Index.'
    } else {
        Write-Host ''
        Write-UabsStep ("indexing {0} project(s), mode={1}" -f $targets.Count, $IndexMode)
        $results = @()
        foreach ($t in $targets) { $results += Invoke-CbmIndex -Exe $exe -ProjectRoot $t -Mode $IndexMode }
        Write-Host ''
        Write-UabsStep 'index results'
        Write-Host ('  {0,-44} {1,7} {2,8} {3,5} {4,5}  {5}' -f 'project', 'nodes', 'edges', 'excl', 'secs', 'status')
        foreach ($r in $results) {
            $nodesTxt = if ($null -eq $r.Nodes) { '-' } else { [string]$r.Nodes }
            Write-Host ('  {0,-44} {1,7} {2,8} {3,5} {4,5}  {5}' -f $r.Name, $nodesTxt, [string]$r.Edges, [string]$r.Excluded, [string]$r.Secs, $r.Status)
        }
        Write-Host ''
        $failed = @($results | Where-Object { $_.Status -ne 'indexed' }).Count
        $sum = [int](($results | Measure-Object -Property Nodes -Sum).Sum)
        if ($failed -gt 0) {
            Write-UabsWarn ("{0} of {1} failed; total nodes {2}" -f $failed, $results.Count, $sum)
            exit $failed
        }
        Write-UabsOk ("all {0} indexed; total nodes {1}" -f $results.Count, $sum)
    }
} else {
    Write-Host '  Index next with -Index, or: index_repository(repo_path=<root>, mode=moderate, name=<stable-slug>)'
}

Write-Host '  Then: check node count against file count, and confirm languages with'
Write-Host '        get_architecture(aspects=["languages"]).'
Write-Host '  Note: Papyrus (.psc) is never parsed - a tiny graph for a script-only mod is correct.'
